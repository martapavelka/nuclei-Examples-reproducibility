#!/usr/bin/env python3
"""Exhaustive search for nontrivial nuclei on at most 10 vertices.

Boundary spheres are generated by plantri. For each sphere, a 0/1 MILP enumerates
all tetrahedral pseudomanifold fillings satisfying the nucleus reducedness rule,
the proven all-interior-tetrahedron condition, and t <= C(v,2)-2v+3.
Every integer solution is then checked independently using exact combinatorics:
boundary, triangle incidences, reducedness, dual connectivity, vertex/edge links,
and F_2 homology. Any survivor is written to disk; zero survivors proves the
claimed finite statement, subject only to correctness/exhaustiveness of plantri
and the MILP solver.

Requires: Python >=3.10, scipy, networkx, and a compiled plantri executable.
The program can build plantri from a supplied plantri source directory.
"""
from __future__ import annotations
import argparse, hashlib, itertools as it, json, math, os, re, subprocess, sys, time
from collections import Counter, defaultdict, deque
from pathlib import Path
import numpy as np
from scipy.optimize import milp, Bounds, LinearConstraint
from scipy.sparse import lil_matrix, vstack, csr_matrix


def sha256(path):
    h=hashlib.sha256()
    with open(path,'rb') as f:
        for b in iter(lambda:f.read(1<<20),b''): h.update(b)
    return h.hexdigest()

def plantri_ascii(exe,n):
    p=subprocess.run([str(exe),'-a',str(n)],capture_output=True,text=True,check=True)
    return [x for x in p.stdout.splitlines() if x.strip()]

def parse_ascii(line):
    # plantri ascii: "6 bcdef,afec,..."; letters a,b,... are vertices 0,1,...
    n_s, rest=line.strip().split(maxsplit=1); n=int(n_s)
    adj=[]
    for s in rest.split(','):
        adj.append([ord(c)-97 for c in s.strip()])
    assert len(adj)==n
    return adj

def sphere_faces(adj):
    # Face-trace the oriented planar embedding. Successor convention may reverse
    # orientation but gives the same triangular face sets.
    seen=set(); faces=[]
    for u in range(len(adj)):
        for v in adj[u]:
            if (u,v) in seen: continue
            cyc=[]; a,b=u,v
            while (a,b) not in seen:
                seen.add((a,b)); cyc.append(a)
                nb=adj[b]; j=nb.index(a)
                a,b=b,nb[(j-1)%len(nb)]
            if len(cyc)!=3: raise ValueError(f'non-triangular face {cyc}')
            faces.append(tuple(sorted(cyc)))
    faces=sorted(set(faces))
    if len(faces)!=2*len(adj)-4: raise ValueError('wrong face count')
    return faces

def all_subfaces(facets,k):
    return {tuple(sorted(s)) for f in facets for s in it.combinations(f,k)}

def gf2_rank(rows,ncols):
    piv={}; r=0
    for xs in rows:
        x=0
        for j in xs: x ^= 1<<j
        while x:
            p=x.bit_length()-1
            if p in piv: x ^= piv[p]
            else: piv[p]=x; r+=1; break
    return r

def betti_f2(tets):
    simplices={k:sorted(all_subfaces(tets,k+1)) for k in range(4)}
    idx={k:{s:i for i,s in enumerate(simplices[k])} for k in range(4)}
    ranks=[0]
    for k in range(1,4):
        rows=[]
        for s in simplices[k]: rows.append([idx[k-1][tuple(x for x in s if x!=v)] for v in s])
        ranks.append(gf2_rank(rows,len(simplices[k-1])))
    b=[]
    for k in range(4):
        rk=ranks[k] if k else 0
        rkp1=ranks[k+1] if k<3 else 0
        b.append(len(simplices[k])-rk-rkp1)
    return b

def graph_connected(edges, vertices):
    if not vertices:return True
    A=defaultdict(set)
    for a,b in edges:A[a].add(b);A[b].add(a)
    q=[next(iter(vertices))]; seen=set(q)
    for a in q:
        for b in A[a]:
            if b not in seen:seen.add(b);q.append(b)
    return seen==set(vertices)

def link_complex(tets, sigma):
    S=set(sigma); out=[]
    for T in tets:
        if S<=set(T): out.append(tuple(sorted(set(T)-S)))
    return out

def check_1manifold_link(edges, want_cycle):
    E={tuple(sorted(e)) for e in edges if len(e)==2}
    V={x for e in E for x in e}
    if not V or not graph_connected(E,V): return False
    d=Counter(x for e in E for x in e)
    if want_cycle:return all(d[x]==2 for x in V)
    return sum(d[x]==1 for x in V)==2 and all(d[x] in (1,2) for x in V)

def check_disk_link(tris):
    F={tuple(sorted(f)) for f in tris if len(f)==3};
    if not F:return False
    E=Counter(tuple(sorted(e)) for f in F for e in it.combinations(f,2))
    if any(c not in (1,2) for c in E.values()):return False
    V={x for f in F for x in f}
    # connected triangle adjacency
    A=[]
    fl=list(F)
    for i in range(len(fl)):
        for j in range(i):
            if len(set(fl[i])&set(fl[j]))==2:A.append((i,j))
    if not graph_connected(A,set(range(len(fl)))):return False
    bd=[e for e,c in E.items() if c==1]
    if not check_1manifold_link(bd,True):return False
    return len(V)-len(E)+len(F)==1

def exact_check(tets,bfaces,n):
    tets=[tuple(sorted(T)) for T in tets]; bfaces=set(map(tuple,bfaces))
    tc=Counter(tuple(sorted(f)) for T in tets for f in it.combinations(T,3))
    actual_b={f for f,c in tc.items() if c==1}
    if actual_b!=bfaces:return False,'boundary'
    if any(c not in (1,2) for c in tc.values()):return False,'triangle-incidence'
    bedges=all_subfaces(bfaces,2)
    for f,c in tc.items():
        if c==2 and sum(tuple(sorted(e)) in bedges for e in it.combinations(f,2))>1:
            return False,'reducedness'
    # dual connectivity
    owners=defaultdict(list)
    for i,T in enumerate(tets):
        for f in it.combinations(T,3):owners[tuple(sorted(f))].append(i)
    de=[tuple(v) for v in owners.values() if len(v)==2]
    if not graph_connected(de,set(range(len(tets)))):return False,'dual-disconnected'
    # all vertices have disk links; every used edge interval/circle according to boundary
    for v in range(n):
        if not check_disk_link(link_complex(tets,(v,))):return False,f'vertex-link-{v}'
    edges=all_subfaces(tets,2)
    for e in edges:
        if not check_1manifold_link(link_complex(tets,e), e not in bedges):
            return False,f'edge-link-{e}'
    b=betti_f2(tets)
    if b!=[1,0,0,0]:return False,f'homology-{b}'
    return True,'survivor'

def build_model(n,bfaces):
    V=range(n); bfaces=set(map(tuple,bfaces)); bedges=all_subfaces(bfaces,2)
    tris=list(it.combinations(V,3)); tri_i={f:i for i,f in enumerate(tris)}
    forbidden={f for f in tris if f not in bfaces and sum(tuple(sorted(e)) in bedges for e in it.combinations(f,2))>=2}
    tets=[]
    for T in it.combinations(V,4):
        if any(tuple(sorted(f)) in forbidden for f in it.combinations(T,3)):continue
        tets.append(T)
    # x_T plus y_F for nonboundary, nonforbidden triangles. z_e for nonboundary edges.
    inttris=[f for f in tris if f not in bfaces and f not in forbidden]
    edges=list(it.combinations(V,2)); intedges=[e for e in edges if e not in bedges]
    nx=len(tets); ny=len(inttris); nz=len(intedges); N=nx+ny+nz
    yi={f:nx+i for i,f in enumerate(inttris)}; zi={e:nx+ny+i for i,e in enumerate(intedges)}
    rows=[]; lo=[]; hi=[]
    def add(coeff,l,h):rows.append(coeff);lo.append(l);hi.append(h)
    # triangle equations
    for f in tris:
        inc=[i for i,T in enumerate(tets) if set(f)<=set(T)]
        c={i:1 for i in inc}
        if f in bfaces:add(c,1,1)
        elif f in forbidden:add(c,0,0)
        else:c[yi[f]]=-2;add(c,0,0)
    # edge-presence z_e iff at least one incident tet: x<=z and z<=sum x
    for e in intedges:
        inc=[i for i,T in enumerate(tets) if set(e)<=set(T)]
        z=zi[e]
        for i in inc:add({i:1,z:-1},-np.inf,0)
        c={z:1};c.update({i:-1 for i in inc});add(c,-np.inf,0)
    # t bound
    tmax=math.comb(n,2)-2*n+3;add({i:1 for i in range(nx)},-np.inf,tmax)
    # nontrivial and structural theorem: at least one tet all six edges interior
    interior_tets=[i for i,T in enumerate(tets) if all(tuple(sorted(e)) not in bedges for e in it.combinations(T,2))]
    if not interior_tets:return None
    add({i:1 for i in interior_tets},1,np.inf)
    # Euler characteristic of each vertex link = 1.  Link V are incident edges,
    # link E are incident triangles, link F are incident tetrahedra.
    # Boundary edges/triangles contribute constants; interior edge/tri presence use z/y.
    for v in V:
        c={}; const=0
        for e in edges:
            if v not in e:continue
            if e in bedges:const+=1
            else:c[zi[e]]=c.get(zi[e],0)+1
        for f in tris:
            if v not in f:continue
            if f in bfaces:const-=1
            elif f in forbidden:pass
            else:c[yi[f]]=c.get(yi[f],0)-1
        for i,T in enumerate(tets):
            if v in T:c[i]=c.get(i,0)+1
        add(c,1-const,1-const)
    A=lil_matrix((len(rows),N),dtype=float)
    for r,c in enumerate(rows):
        for j,a in c.items():A[r,j]=a
    return dict(tets=tets,nx=nx,N=N,A=csr_matrix(A),lo=np.array(lo),hi=np.array(hi),tmax=tmax,
                bfaces=sorted(bfaces),bedges=bedges)

def enumerate_fillings(model,n,limit=None):
    A=model['A']; lo=model['lo']; hi=model['hi']; nx=model['nx']; N=model['N']; tets=model['tets']
    blocks=[]; count=0
    while True:
        AA=vstack([A]+[x[0] for x in blocks],format='csr') if blocks else A
        LL=np.concatenate([lo]+[x[1] for x in blocks]) if blocks else lo
        HH=np.concatenate([hi]+[x[2] for x in blocks]) if blocks else hi
        res=milp(np.zeros(N),integrality=np.ones(N),bounds=Bounds(np.zeros(N),np.ones(N)),
                 constraints=LinearConstraint(AA,LL,HH),options={'presolve':True})
        if not res.success:
            if res.status==2:return
            raise RuntimeError(f'MILP failed status={res.status}: {res.message}')
        bits=np.rint(res.x[:nx]).astype(int)
        if np.max(np.abs(res.x[:nx]-bits))>1e-6:raise RuntimeError('nonintegral MILP result')
        chosen=[tets[i] for i,b in enumerate(bits) if b]
        yield chosen
        count+=1
        if limit and count>=limit:return
        ones=np.flatnonzero(bits); zeros=np.flatnonzero(1-bits)
        # no-good: sum_ones x - sum_zeros x <= |ones|-1
        rr=lil_matrix((1,N));
        for i in ones:rr[0,i]=1
        for i in zeros:rr[0,i]=-1
        blocks.append((csr_matrix(rr),np.array([-np.inf]),np.array([len(ones)-1.])))

def main():
    ap=argparse.ArgumentParser()
    ap.add_argument('--plantri',required=True,type=Path)
    ap.add_argument('--min-v',type=int,default=4);ap.add_argument('--max-v',type=int,default=10)
    ap.add_argument('--out',type=Path,default=Path('nucleus_lb_output'))
    ap.add_argument('--limit-models',type=int,default=None,help='debug only; invalidates exhaustion')
    a=ap.parse_args();a.out.mkdir(parents=True,exist_ok=True)
    log={'program_sha256':sha256(__file__),'plantri':str(a.plantri),'plantri_sha256':sha256(a.plantri),
         'min_v':a.min_v,'max_v':a.max_v,'started':time.strftime('%FT%T%z'),'vertices':{},'survivors':[]}
    total_spheres=total_models=0
    for n in range(a.min_v,a.max_v+1):
        lines=plantri_ascii(a.plantri,n); total_spheres+=len(lines); vd={'spheres':len(lines),'models':0,'rejections':Counter(),'survivors':0}
        raw='\n'.join(lines)+'\n'; (a.out/f'boundaries_v{n}.asc').write_text(raw);vd['boundary_sha256']=hashlib.sha256(raw.encode()).hexdigest()
        print(f'v={n}: {len(lines)} boundary spheres',flush=True)
        for si,line in enumerate(lines):
            bf=sphere_faces(parse_ascii(line)); model=build_model(n,bf)
            if model is None:continue
            for chosen in enumerate_fillings(model,n,a.limit_models):
                vd['models']+=1;total_models+=1
                ok,why=exact_check(chosen,bf,n);vd['rejections'][why]+=1
                if ok:
                    vd['survivors']+=1
                    rec={'v':n,'sphere_index':si,'facets':[list(x) for x in chosen]};log['survivors'].append(rec)
                    (a.out/f'SURVIVOR_v{n}_{si}.json').write_text(json.dumps(rec,indent=2))
            if (si+1)%25==0:print(f'  {si+1}/{len(lines)}; models {vd["models"]}; survivors {vd["survivors"]}',flush=True)
        vd['rejections']=dict(vd['rejections']);log['vertices'][str(n)]=vd
        (a.out/'run.json').write_text(json.dumps(log,indent=2))
    log['finished']=time.strftime('%FT%T%z');log['total_spheres']=total_spheres;log['total_models']=total_models
    log['exhaustive']=a.limit_models is None;log['theorem_certified_by_run']=bool(log['exhaustive'] and not log['survivors'])
    (a.out/'run.json').write_text(json.dumps(log,indent=2))
    print(json.dumps({k:log[k] for k in ('total_spheres','total_models','exhaustive','theorem_certified_by_run')},indent=2))
    if log['survivors']:sys.exit(2)

if __name__=='__main__':main()
